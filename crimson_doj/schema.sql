CREATE TABLE IF NOT EXISTS crimson_mdt_entries (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT,
 scope VARCHAR(80) NOT NULL,
 kind VARCHAR(24) NOT NULL,
 subject VARCHAR(80) NOT NULL DEFAULT '',
 title VARCHAR(160) NOT NULL,
 body MEDIUMTEXT NOT NULL,
 details LONGTEXT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'open',
 owner VARCHAR(64) NOT NULL,
 updated_by VARCHAR(64) NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id), KEY scope_kind(scope,kind,status), KEY subject_scope(subject,scope)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS crimson_mdt_audit (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 scope VARCHAR(80) NOT NULL,
 actor VARCHAR(64) NOT NULL,
 action VARCHAR(40) NOT NULL,
 record_id INT UNSIGNED DEFAULT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(id), KEY scope_id(scope,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS crimson_mdt_state (
 scope VARCHAR(80) NOT NULL,
 threat VARCHAR(16) NOT NULL DEFAULT 'green',
 PRIMARY KEY(scope)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS crimson_mdt_migrations (
 name VARCHAR(64) NOT NULL PRIMARY KEY,
 applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS crimson_mdt_prints (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 ticket VARCHAR(64) NOT NULL,
 record_id INT UNSIGNED NOT NULL,
 snapshot LONGTEXT NOT NULL,
 issued_by VARCHAR(64) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(id), UNIQUE KEY ticket(ticket)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS crimson_mdt_payments (
 entry_id INT UNSIGNED NOT NULL,
 kind VARCHAR(16) NOT NULL,
 payer VARCHAR(64) NOT NULL,
 account VARCHAR(80) NOT NULL,
 amount INT UNSIGNED NOT NULL,
 reason VARCHAR(1000) NOT NULL DEFAULT '',
 state VARCHAR(24) NOT NULL,
 error_note VARCHAR(160) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(entry_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS crimson_mdt_custody (
 entry_id INT UNSIGNED NOT NULL,
 citizenid VARCHAR(64) NOT NULL,
 minutes INT UNSIGNED NOT NULL,
 actor VARCHAR(64) NOT NULL,
 reason VARCHAR(1000) NOT NULL DEFAULT '',
 state VARCHAR(24) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(entry_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
