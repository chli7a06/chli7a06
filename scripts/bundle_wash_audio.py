"""Keep audio inside the existing, always-loaded wash HUD entry point."""
from pathlib import Path
import base64
import io
import json
import wave

root = Path(__file__).resolve().parents[1] / 'crimson-mechanic/web'
marker = '// BEGIN BUNDLED WASH AUDIO (generated by scripts/bundle_wash_audio.py)'
hud = (root / 'wash.js').read_text().split(marker, 1)[0].rstrip()
audio = (root / 'wash-audio.js').read_text().rstrip()
sources = {}
for kind in ['water', 'foam']:
    payload = (root / 'audio' / f'wash_{kind}.wav').read_bytes()
    with wave.open(io.BytesIO(payload)) as decoded:
        assert decoded.getnchannels() == 1 and decoded.getsampwidth() == 2
        assert decoded.getframerate() == 22050 and decoded.getnframes() == 88200
    sources[kind] = 'data:audio/wav;base64,' + base64.b64encode(payload).decode('ascii')
embedded = 'window.CrimsonWashAudioData=' + json.dumps(sources, separators=(',', ':')) + ';\n'
(root / 'wash.js').write_text(hud + '\n\n' + marker + '\n' + embedded + audio + '\n')
print('Bundled player and inline PCM WAV into wash.js; no audio URL/file request needed')
